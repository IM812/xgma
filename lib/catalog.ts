function m(category: string, model: string, summary: string, specs: [string, string][], slug?: string): Machine {
  return {
    slug: slug ?? model.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''),
    model,
    category,
    summary,
    specs: specs.map(([label, value]) => ({ label, value })),
  }
}

